import 'adhkar_extra.dart';
import 'app_locale.dart';

class Dhikr {
  final String id;
  final String title;
  final String arabic;
  final String transliteration;
  final String meaning;
  final String source;
  final int count;
  final String? note;

  const Dhikr({
    required this.id,
    required this.title,
    required this.arabic,
    required this.transliteration,
    required this.meaning,
    required this.source,
    this.count = 1,
    this.note,
  });

  // ---- English texts, references and audio live in adhkar_extra.dart ----

  DhikrExtra? get extra => adhkarExtra[id];

  String get shownTitle =>
      AppLocale.isBangla ? title : (extra?.title ?? title);

  String get shownTransliteration => AppLocale.isBangla
      ? transliteration
      : (extra?.transliteration ?? transliteration);

  String get shownMeaning =>
      AppLocale.isBangla ? meaning : (extra?.meaning ?? meaning);

  String? get shownNote =>
      AppLocale.isBangla ? note : (extra?.note ?? note);

  /// Asset path inside assets/ (null = no audio for this dua yet).
  String? get audio => extra?.audio;

  /// Book names with hadith numbers, in the selected language.
  String get shownSource {
    final refs = extra?.refs ?? const <Ref>[];

    if (refs.isEmpty) return source;

    final bangla = AppLocale.isBangla;

    return refs.map((ref) {
      final names = refBooks[ref.book];
      var text = names == null ? ref.book : (bangla ? names[0] : names[1]);

      if (ref.number != null) {
        text += bangla
            ? ', হা/${AppLocale.digits(ref.number!)}'
            : ', no. ${ref.number}';
      }

      if (ref.grade != null) {
        final grade = ref.grade == 'hasan'
            ? (bangla ? 'সনদ হাসান' : 'hasan')
            : (bangla ? 'সনদ সহীহ' : 'sahih');

        text += ' ($grade)';
      }

      return text;
    }).join('; ');
  }
}

